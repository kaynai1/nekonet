import { spawn, type ChildProcess } from 'node:child_process'
import crypto from 'node:crypto'
import fs from 'node:fs'
import http from 'node:http'
import path from 'node:path'
import { app } from 'electron'
import type { CoreConfig, CoreStatus } from '@shared/types'
import { run } from '../scanner/exec'

const MIXED_PORT = 7890
const CONTROLLER_PORT = 9090
const CONTROLLER_URL = `http://127.0.0.1:${CONTROLLER_PORT}`

interface ProxyBackup {
  proxyEnable: string | null
  proxyServer: string | null
  proxyOverride: string | null
}

function coreDir(): string {
  return path.join(app.getPath('userData'), 'core')
}

function binaryPath(): string {
  const name = process.platform === 'win32' ? 'mihomo.exe' : 'mihomo'
  const candidates = app.isPackaged
    ? [path.join(process.resourcesPath, 'mihomo', name)]
    : [
        path.join(app.getAppPath(), 'resources', 'mihomo', name),
        path.join(process.cwd(), 'resources', 'mihomo', name)
      ]
  return candidates.find((file) => fs.existsSync(file)) ?? candidates[0]
}

function readSecret(): string {
  const file = path.join(coreDir(), 'secret.txt')
  try {
    const existing = fs.readFileSync(file, 'utf8').trim()
    if (existing.length >= 16) return existing
  } catch {
    /* generate below */
  }
  const secret = crypto.randomBytes(16).toString('hex')
  fs.mkdirSync(coreDir(), { recursive: true })
  fs.writeFileSync(file, secret, 'utf8')
  return secret
}

function yamlString(value: string): string {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
}

function buildConfig(config: CoreConfig, secret: string): string {
  const lines: string[] = [
    '# Generated by NekoNet. Manual edits are overwritten on start.',
    `mixed-port: ${MIXED_PORT}`,
    // 只给本机用：分享安装包后不会在局域网里暴露 7890 端口
    `allow-lan: false`,
    `bind-address: "127.0.0.1"`,
    'mode: rule',
    'log-level: warning',
    'ipv6: false',
    `external-controller: 127.0.0.1:${CONTROLLER_PORT}`,
    `secret: ${yamlString(secret)}`,
    'profile:',
    '  store-selected: true',
    'dns:',
    '  enable: true',
    '  ipv6: false',
    '  enhanced-mode: fake-ip',
    '  fake-ip-range: 198.18.0.1/16',
    '  nameserver:',
    '    - 223.5.5.5',
    '    - 119.29.29.29',
    // 规则只用 MATCH，无需 GeoIP/GeoSite，避免内核联网下载 MMDB 失败而退出
    'geo-auto-update: false'
  ]

  const url = config.subscriptionUrl.trim()
  if (url) {
    lines.push(
      'proxy-providers:',
      '  nekonet:',
      '    type: http',
      `    url: ${yamlString(url)}`,
      '    path: ./providers/nekonet.yaml',
      '    interval: 86400',
      '    health-check:',
      '      enable: true',
      '      url: https://www.gstatic.com/generate_204',
      '      interval: 300',
      'proxy-groups:',
      '  - name: NekoNet',
      '    type: select',
      '    use:',
      '      - nekonet',
      '    proxies:',
      '      - DIRECT',
      'rules:',
      '  - MATCH,NekoNet'
    )
  } else {
    lines.push('proxy-groups:', '  - name: NekoNet', '    type: select', '    proxies:', '      - DIRECT', 'rules:', '  - MATCH,DIRECT')
  }

  return `${lines.join('\n')}\n`
}

function waitForController(secret: string, timeoutMs: number): Promise<{ ok: boolean; version: string | null; error: string | null }> {
  const deadline = Date.now() + timeoutMs
  return new Promise((resolve) => {
    const attempt = (): void => {
      const req = http.request(
        `${CONTROLLER_URL}/version`,
        { method: 'GET', timeout: 900, headers: { Authorization: `Bearer ${secret}` } },
        (res) => {
          let body = ''
          res.setEncoding('utf8')
          res.on('data', (chunk: string) => {
            if (body.length < 20_000) body += chunk
          })
          res.on('end', () => {
            if (res.statusCode === 200) {
              let version: string | null = null
              try {
                version = (JSON.parse(body) as { version?: string }).version ?? null
              } catch {
                version = null
              }
              resolve({ ok: true, version, error: null })
              return
            }
            retry()
          })
        }
      )
      req.on('timeout', () => {
        req.destroy()
        retry()
      })
      req.on('error', () => retry())
      req.end()
    }
    const retry = (): void => {
      if (Date.now() > deadline) {
        resolve({ ok: false, version: null, error: '内核启动超时（端口 9090 未响应）' })
        return
      }
      setTimeout(attempt, 320)
    }
    attempt()
  })
}

export class MihomoCore {
  private child: ChildProcess | null = null
  private secret = ''
  private status: CoreStatus = {
    running: false,
    available: fs.existsSync(binaryPath()),
    version: null,
    port: MIXED_PORT,
    error: null,
    systemProxy: false
  }
  private logTail = ''
  private listener: ((status: CoreStatus) => void) | null = null
  private stopping = false

  onStatus(cb: (status: CoreStatus) => void): void {
    this.listener = cb
  }

  getStatus(): CoreStatus {
    return { ...this.status }
  }

  get controller(): { url: string; secret: string } {
    return { url: CONTROLLER_URL, secret: this.secret }
  }

  private setStatus(patch: Partial<CoreStatus>): void {
    this.status = { ...this.status, ...patch }
    this.listener?.(this.getStatus())
  }

  private writeConfig(config: CoreConfig): void {
    fs.mkdirSync(coreDir(), { recursive: true })
    fs.writeFileSync(path.join(coreDir(), 'config.yaml'), buildConfig(config, this.secret), 'utf8')
  }

  async start(config: CoreConfig): Promise<CoreStatus> {
    if (!this.status.available) {
      this.setStatus({ running: false, error: '安装包中缺少 mihomo 内核文件' })
      return this.getStatus()
    }
    if (this.child) return this.getStatus()

    this.secret = readSecret()
    this.writeConfig(config)
    this.logTail = ''
    this.stopping = false

    const child = spawn(binaryPath(), ['-d', coreDir(), '-f', path.join(coreDir(), 'config.yaml')], {
      cwd: coreDir(),
      windowsHide: true,
      stdio: ['ignore', 'pipe', 'pipe']
    })
    this.child = child

    const capture = (chunk: Buffer): void => {
      this.logTail = (this.logTail + chunk.toString('utf8')).slice(-4000)
    }
    child.stdout?.on('data', capture)
    child.stderr?.on('data', capture)

    child.once('error', (error) => {
      if (this.child !== child) return
      this.child = null
      this.setStatus({ running: false, error: `内核启动失败：${error.message}` })
    })

    child.once('exit', (code) => {
      if (this.child !== child) return
      this.child = null
      const wasStopping = this.stopping
      this.stopping = false
      const detail = wasStopping ? null : lastLines(this.logTail) || `内核已退出（code ${code ?? '?'}）`
      this.setStatus({ running: false, version: null, error: detail, systemProxy: this.status.systemProxy })
      if (!wasStopping) void disableSystemProxy()
    })

    const ready = await waitForController(this.secret, 12_000)
    if (!ready.ok) {
      const detail = lastLines(this.logTail)
      this.stop()
      this.setStatus({ running: false, error: detail ? `${ready.error}：${detail}` : ready.error })
      return this.getStatus()
    }

    this.setStatus({ running: true, version: ready.version, error: null })
    return this.getStatus()
  }

  stop(): void {
    if (!this.child) {
      this.setStatus({ running: false, version: null })
      return
    }
    this.stopping = true
    const child = this.child
    try {
      child.kill()
    } catch {
      /* ignore */
    }
    this.child = null
    this.setStatus({ running: false, version: null, error: null })
  }

  dispose(): void {
    this.stop()
  }
}

function lastLines(text: string): string | null {
  const lines = text
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean)
  if (!lines.length) return null
  return lines.slice(-2).join(' | ').slice(0, 300)
}

const BACKUP_FILE = (): string => path.join(app.getPath('userData'), 'core', 'system-proxy-backup.json')

const PROXY_KEY = 'HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Internet Settings'

async function readRegistryValue(name: string): Promise<string | null> {
  try {
    const out = await run('reg', ['query', PROXY_KEY, '/v', name], 4000)
    const match = out.match(new RegExp(`${name}\\s+REG_\\w+\\s+(.+)`, 'i'))
    return match ? match[1].trim() : null
  } catch {
    return null
  }
}

async function refreshWinInet(): Promise<void> {
  const script = [
    '$sig = \'[DllImport("wininet.dll", SetLastError=true)] public static extern bool InternetSetOption(IntPtr h, int o, IntPtr b, int l);\'',
    '$t = Add-Type -MemberDefinition $sig -Name WinInetNeko -Namespace NekoNet -PassThru',
    '[void]$t::InternetSetOption([IntPtr]::Zero, 39, [IntPtr]::Zero, 0)',
    '[void]$t::InternetSetOption([IntPtr]::Zero, 37, [IntPtr]::Zero, 0)'
  ].join('; ')
  try {
    await run('powershell', ['-NoProfile', '-NonInteractive', '-Command', script], 8000)
  } catch {
    /* best effort */
  }
}

let proxyError: string | null = null

export function lastSystemProxyError(): string | null {
  return proxyError
}

export async function enableSystemProxy(port = MIXED_PORT): Promise<boolean> {
  if (process.platform !== 'win32') {
    proxyError = '当前系统不支持自动设置系统代理'
    return false
  }
  try {
    fs.mkdirSync(coreDir(), { recursive: true })
    if (!fs.existsSync(BACKUP_FILE())) {
      const backup: ProxyBackup = {
        proxyEnable: await readRegistryValue('ProxyEnable'),
        proxyServer: await readRegistryValue('ProxyServer'),
        proxyOverride: await readRegistryValue('ProxyOverride')
      }
      fs.writeFileSync(BACKUP_FILE(), JSON.stringify(backup), 'utf8')
    }
    await run('reg', ['add', PROXY_KEY, '/v', 'ProxyEnable', '/t', 'REG_DWORD', '/d', '1', '/f'], 4000)
    await run('reg', ['add', PROXY_KEY, '/v', 'ProxyServer', '/t', 'REG_SZ', '/d', `127.0.0.1:${port}`, '/f'], 4000)
    await run('reg', ['add', PROXY_KEY, '/v', 'ProxyOverride', '/t', 'REG_SZ', '/d', '<local>', '/f'], 4000)
    await refreshWinInet()
    proxyError = null
    return true
  } catch (error) {
    proxyError = (error as Error).message.slice(0, 160)
    return false
  }
}

export async function disableSystemProxy(): Promise<void> {
  if (process.platform !== 'win32') return
  // 没有备份说明不是本应用改的，不要动用户自己的代理设置
  if (!fs.existsSync(BACKUP_FILE())) return
  try {
    let backup: ProxyBackup | null = null
    try {
      backup = JSON.parse(fs.readFileSync(BACKUP_FILE(), 'utf8')) as ProxyBackup
    } catch {
      backup = null
    }
    const enable = backup?.proxyEnable
    const enabledBefore = enable !== null && enable !== undefined && enable !== '0x0'
    await run('reg', ['add', PROXY_KEY, '/v', 'ProxyEnable', '/t', 'REG_DWORD', '/d', enabledBefore ? '1' : '0', '/f'], 4000)
    if (enabledBefore && backup?.proxyServer) {
      await run('reg', ['add', PROXY_KEY, '/v', 'ProxyServer', '/t', 'REG_SZ', '/d', backup.proxyServer, '/f'], 4000)
      if (backup.proxyOverride) {
        await run('reg', ['add', PROXY_KEY, '/v', 'ProxyOverride', '/t', 'REG_SZ', '/d', backup.proxyOverride, '/f'], 4000)
      }
    }
    await refreshWinInet()
    fs.rmSync(BACKUP_FILE(), { force: true })
  } catch {
    /* best effort */
  }
}
